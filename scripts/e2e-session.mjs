#!/usr/bin/env node
// Browser check of 「このセッションの変更」 and the mouse wheel against a running server (needs Google Chrome). The model is changed
// through MCP, so use a copy of a model with an event and a hotspot (for example test/model/fixtures/sample).
//   node scripts/e2e-session.mjs <server-url> <project-slug> <screenshot-dir>
import { chromium } from 'playwright-core';
import { Client } from '@modelcontextprotocol/sdk/client/index.js';
import { StreamableHTTPClientTransport } from '@modelcontextprotocol/sdk/client/streamableHttp.js';
const [url, slug, out] = process.argv.slice(2);
let fails = 0;
const ok = (n, c, d = '') => { if (!c) fails++; console.log(`${c ? 'ok  ' : 'FAIL'} ${n} ${d}`); };
const mcp = new Client({ name: 'claude-code', version: '1.0.0' });
await mcp.connect(new StreamableHTTPClientTransport(new URL(`${url}/mcp`)));
const call = async (name, args) => JSON.parse((await mcp.callTool({ name, arguments: args })).content[0].text);
const bp = async () => { const m = await call('get_model', { project: slug }); return { version: m.version, nodes: m.data['big-picture'].nodes }; };
const b = await chromium.launch({ channel: 'chrome' });
const p = await b.newPage({ viewport: { width: 1440, height: 900 } });
await p.goto(`${url}/#/${slug}/big-picture.html`);
await p.waitForFunction(() => document.querySelector('iframe')?.contentDocument?.getElementById('board'));
await p.waitForTimeout(600);
const f = () => p.frames().find((x) => x.url().endsWith('/pages/big-picture.html'));
ok('bar shows the base', /ボードを開いた時点（版 \d+）/.test(await p.textContent('#base-label')), await p.textContent('#base-label'));
ok('empty list at first', /まだ変更はありません/.test(await p.textContent('#changes')));
let m = await bp();
const target = m.nodes.find((n) => n.type === 'event' && !n.attach);
let r = await call('apply_changes', { project: slug, base_version: m.version, ops: [{ op: 'addNode', after: target.id, node: { type: 'hotspot', text: '会議で出た疑問（テスト）' } }, { op: 'updateNode', id: target.id, patch: { text: target.text + '（直した）' } }] });
await p.waitForTimeout(1500);
const added = r.summary.added[0];
ok('added sticky framed', await f().evaluate((id) => document.getElementById('n-' + id)?.classList.contains('esm-s-added'), added));
ok('updated sticky framed', await f().evaluate((id) => document.getElementById('n-' + id)?.classList.contains('esm-s-updated'), target.id));
ok('list has 2 stickies + 1 arrow', /このセッションの変更 \(3\)/.test(await p.textContent('#changes h2')), await p.textContent('#changes h2'));
await p.waitForTimeout(10500);
ok('frames stay after 10 s', await f().evaluate((id) => document.getElementById('n-' + id)?.classList.contains('esm-s-added'), added));
await p.click('#changes button.chg.added');
await p.waitForTimeout(900);
await p.screenshot({ path: out + '/diff-1.png' });
await p.reload();
await p.waitForFunction(() => document.querySelector('iframe')?.contentDocument?.getElementById('board'));
await p.waitForTimeout(1200);
ok('reload keeps the diff', /このセッションの変更 \(3\)/.test(await p.textContent('#changes h2')));
m = await bp();
await call('apply_changes', { project: slug, base_version: m.version, ops: [{ op: 'removeNode', id: added }] });
await p.waitForTimeout(1500);
ok('added then removed disappears', /このセッションの変更 \(1\)/.test(await p.textContent('#changes h2')), await p.textContent('#changes h2'));
m = await bp();
const victim = m.nodes.find((n) => n.type === 'hotspot');
await call('apply_changes', { project: slug, base_version: m.version, ops: [{ op: 'removeNode', id: victim.id }] });
await p.waitForTimeout(1500);
ok('removed sticky struck through', (await p.locator('#changes button.chg.removed').count()) >= 1);
await p.screenshot({ path: out + '/diff-2.png' });
await p.uncheck('#show-changes'); await p.waitForTimeout(600);
ok('toggle hides frames and list', !(await f().evaluate(() => !!document.querySelector('.esm-s-updated'))) && await p.locator('#changes').isHidden());
await p.check('#show-changes'); await p.waitForTimeout(600);
await p.click('#rebase'); await p.waitForTimeout(900);
ok('rebase empties the list', /まだ変更はありません/.test(await p.textContent('#changes')) && /選んだ版/.test(await p.textContent('#base-label')));
await p.goto(`${url}/#/${slug}/history`); await p.waitForTimeout(900);
await p.click('#h-items li:nth-child(3) button'); await p.waitForTimeout(600);
await p.click('[data-compare]'); await p.waitForTimeout(1800);
ok('history compare sets the base', /選んだ版（版 \d+）/.test(await p.textContent('#base-label')) && /このセッションの変更 \([1-9]/.test(await p.textContent('#changes h2')), (await p.textContent('#base-label')) + ' ' + (await p.textContent('#changes h2')));


// The wheel: with no vertical room the page scrolls; at 100 % the board scrolls; the board ends inside the frame.
await p.goto(`${url}/#/${slug}/big-picture.html`);
await p.waitForFunction(() => document.querySelector('iframe')?.contentDocument?.getElementById('board'));
await p.waitForTimeout(800);
const box = await p.locator('iframe[title="ドメインモデル"]').boundingBox();
const st = () => f().evaluate(() => { const v = document.querySelector('.zoom-view'); return { top: v.scrollTop, docY: scrollY, bottom: v.getBoundingClientRect().bottom, h: innerHeight, room: v.scrollHeight - v.clientHeight }; });
let s0 = await st();
ok('the board ends inside the frame', s0.bottom <= s0.h, JSON.stringify(s0));
await f().click('.zoom-ctrl [data-z="fit"]'); await p.waitForTimeout(300);
s0 = await st();
const vb = await f().evaluate(() => { const r = document.querySelector('.zoom-view').getBoundingClientRect(); return { x: r.x + r.width / 2, y: r.y + r.height / 2 }; });
await p.mouse.move(box.x + vb.x, box.y + vb.y);
await p.mouse.wheel(0, -300); await p.waitForTimeout(300);
ok('wheel up with no room scrolls the page back to the title', (await st()).docY < s0.docY || s0.docY === 0, JSON.stringify(await st()));
await f().click('.zoom-ctrl [data-z="one"]'); await p.waitForTimeout(300);
await f().evaluate(() => { const v = document.querySelector('.zoom-view'); v.scrollTop = 0; });
const vb2 = await f().evaluate(() => { const r = document.querySelector('.zoom-view').getBoundingClientRect(); return { x: r.x + r.width / 2, y: r.y + Math.min(r.height / 2, 100) }; });
const before = await st();
await p.mouse.move(box.x + vb2.x, box.y + vb2.y);
await p.mouse.wheel(0, 200); await p.waitForTimeout(300);
const after = await st();
ok('wheel at 100% scrolls the board vertically', before.room <= 0 || after.top > before.top, `${before.top} → ${after.top} (room ${before.room})`);
// Blocked storage (private windows): the base and the toggle still hold for the page.
const q = await (await b.newContext({ viewport: { width: 1440, height: 900 } })).newPage();
await q.addInitScript(() => { Storage.prototype.getItem = () => { throw new Error('blocked'); }; Storage.prototype.setItem = () => { throw new Error('blocked'); }; });
await q.goto(`${url}/#/${slug}/big-picture.html`);
await q.waitForFunction(() => document.querySelector('iframe')?.contentDocument?.getElementById('board'));
await q.waitForTimeout(800);
const opened = await q.textContent('#base-label');
m = await bp();
const ev = m.nodes.find((n) => n.type === 'event' && !n.attach);
await call('apply_changes', { project: slug, base_version: m.version, ops: [{ op: 'updateNode', id: ev.id, patch: { text: ev.text + '（ストレージなし）' } }] });
await q.waitForTimeout(1500);
ok('blocked storage keeps the base across a live update', (await q.textContent('#base-label')) === opened && /このセッションの変更 \(1\)/.test(await q.textContent('#changes h2')), `${opened} → ${await q.textContent('#base-label')} / ${await q.textContent('#changes h2')}`);
await q.uncheck('#show-changes'); await q.waitForTimeout(600);
ok('blocked storage keeps the toggle off', !(await q.isChecked('#show-changes')));
await b.close(); await mcp.close();
console.log(fails ? `${fails} failed` : 'all ok');
process.exit(fails ? 1 : 0);
